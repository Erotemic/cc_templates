weather = input("What is the weather: sunny, rainy, or snowy? ")

if weather == "sunny":
    print("Bring sunglasses.")
elif weather == "rainy":
    print("Bring an umbrella.")
elif weather == "snowy":
    print("Bring gloves.")
else:
    print("I do not have a special plan for that weather.")

