# A value can be text, a number, or True / False.
player_name = "Ada"
coins = 3
goal = 5

print("Player:", player_name)
print("Starting coins:", coins)

# An expression combines values to produce another value.
coins_found = 4
coins = coins + coins_found
print("Coins after exploring:", coins)

# A comparison is also an expression. Its value is True or False.
has_enough_coins = coins >= goal
print("Enough coins to enter the fair?", has_enough_coins)

