"""ASCII art for the Star Crystal capstone.

Only the current polished art is kept here.  The old legacy drawings were
useful during the port, but retaining two copies made the capstone harder to
read and edit.  Art remains presentation-only data.
"""

from __future__ import annotations

import textwrap


def _trim(text: str) -> str:
    lines = textwrap.dedent(text).splitlines()
    while lines and not lines[0].strip():
        lines.pop(0)
    while lines and not lines[-1].strip():
        lines.pop()
    return "\n".join(line.rstrip() for line in lines)


def _card(text: str, width: int = 56) -> str:
    """Center a drawing in a terminal-friendly presentation card."""
    lines = _trim(text).splitlines()
    inner = max(width, max((len(line) for line in lines), default=0) + 4)
    top = "+" + "-" * inner + "+"
    body = ["|" + line.center(inner) + "|" for line in lines]
    return "\n".join([top, *body, top])

